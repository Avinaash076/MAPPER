// Optional maintenance command. Fetch actual destination photos and their Commons credits.
// Only stores images whose metadata explicitly supplies a reuse license.
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { Buffer } from 'node:buffer';
const entries = [
  ['unkal-lake', 'Unkal Lake'],
  ['chandramouleshwara', 'Chandramouleshwara Temple, Hubli'],
  ['nrupatunga-betta', 'Nrupatunga Betta'],
  ['siddharoodha', 'Siddharoodha Swami'],
  ['glass-house', 'Indira Gandhi Glass House'],
  ['kelgeri-lake', 'Kelageri'],
  ['sadhankeri', 'Dharwad'],
  ['karnatak-college', 'Karnatak College, Dharwad'],
  ['someshwara', 'Dharwad'],
  ['belagavi-fort', 'Belgaum Fort'],
  ['kamal-basadi', 'Kamal Basadi'],
  ['gokak-falls', 'Gokak Falls'],
  ['godachinmalki', 'Godachinmalki Falls'],
  ['kittur-fort', 'Kittur Fort'],
  ['bhimgad', 'Bhimgad Wildlife Sanctuary'],
];
const clean = (text) =>
  text
    ?.replace(/<[^>]*>/g, '')
    .replace(/&amp;/g, '&')
    .replace(/&#\d+;/g, '')
    .trim();
async function json(url) {
  const response = await fetch(url, {
    headers: { 'User-Agent': 'NorthernTrailsLearningPrototype/1.0' },
    signal: AbortSignal.timeout(20000),
  });
  if (!response.ok) throw new Error(`HTTP ${response.status}`);
  return response.json();
}
const photos = JSON.parse(await readFile('src/features/places/photos.json', 'utf8'));
const files = {
  'unkal-lake': 'Unkal lake.jpg',
  chandramouleshwara: 'The Chandramauleshwara Temple.jpg',
  'kelgeri-lake': 'Kelageri Lake.jpg',
  'karnatak-college': 'Karnatak college (cropped).jpg',
  godachinmalki: 'Godachinmalki falls.jpg',
};
await mkdir('assets/places', { recursive: true });
for (const [id, title] of entries) {
  if (photos[id]) continue;
  // A city or a person's portrait must never stand in for a destination photo.
  if (['siddharoodha', 'sadhankeri', 'someshwara'].includes(id)) continue;
  try {
    const data = await json(
      `https://en.wikipedia.org/w/api.php?action=query&format=json&prop=pageimages&piprop=thumbnail|name&pithumbsize=1000&titles=${encodeURIComponent(title)}`,
    );
    const page = Object.values(data.query.pages)[0];
    const filename = files[id] || page.pageimage;
    if (!filename) continue;
    const meta = await json(
      `https://en.wikipedia.org/w/api.php?action=query&format=json&prop=imageinfo&iiprop=extmetadata|url&iiurlwidth=1000&titles=${encodeURIComponent(`File:${filename}`)}`,
    );
    const imageInfo = Object.values(meta.query.pages)[0]?.imageinfo?.[0];
    const info = imageInfo?.extmetadata;
    if (!info?.LicenseShortName?.value || !info?.Artist?.value) continue;
    const license = clean(info.LicenseShortName.value);
    if (!/CC|Public domain|PDM/i.test(license)) continue;
    const imageUrl = imageInfo.thumburl || imageInfo.url;
    const image = await fetch(imageUrl, { signal: AbortSignal.timeout(20000) });
    if (!image.ok || !image.headers.get('content-type')?.startsWith('image/')) continue;
    await writeFile(`assets/places/${id}.jpg`, Buffer.from(await image.arrayBuffer()));
    photos[id] = {
      uri: imageUrl,
      author: clean(info.Artist.value),
      license,
      sourceUrl: `https://commons.wikimedia.org/wiki/${encodeURIComponent(`File:${filename}`)}`,
      ...(info.LicenseUrl?.value ? { licenseUrl: info.LicenseUrl.value } : {}),
    };
    console.log(`${id}: ${license}`);
  } catch (error) {
    console.log(`${id}: skipped (${error.message})`);
  }
}
await writeFile('src/features/places/photos.json', JSON.stringify(photos, null, 2) + '\n');
await writeFile(
  'src/features/places/photoAssets.ts',
  `/* Generated by scripts/fetch-photos.mjs; bundled for offline use. */\nimport type { ImageSourcePropType } from 'react-native';\nexport const photoAssets: Record<string, ImageSourcePropType> = {\n${Object.keys(
    photos,
  )
    .map((id) => `  '${id}': require('../../../assets/places/${id}.jpg'),`)
    .join('\n')}\n};\n`,
);
